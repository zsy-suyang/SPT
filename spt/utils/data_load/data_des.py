def setup_seed(seed):
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)
    np.random.seed(seed)
    random.seed(seed)
    torch.backends.cudnn.deterministic = True

def filter_and_return_indices(labels, min_samples=3):
    if isinstance(labels, list):
        labels_series = pd.Series(labels)
    else:
        labels_series = pd.Series(labels)

    label_counts = labels_series.value_counts()
    valid_labels = label_counts[label_counts >= min_samples].index
    valid_bools = labels_series.isin(valid_labels)
    valid_indices = np.where(valid_bools)[0]
    return valid_indices


def _is_none_like(value):
    return value is None or str(value).strip().lower() in {"none", "null", ""}


def _group_split_indices(data_df, args):
    """Create deterministic, disjoint parent-structure data partitions."""
    group_column = getattr(args, "group_column", "material_id")
    if group_column not in data_df.columns:
        raise ValueError(
            f"group split requested, but column '{group_column}' is absent from {args.data_file}"
        )

    seed = int(getattr(args, "split_seed", getattr(args, "seed", 42)))
    test_size = float(getattr(args, "test_size", 0.15))
    val_size = float(getattr(args, "val_size", 0.0))
    dev_size = float(getattr(args, "dev_size", 0.0))
    lockbox_size = float(getattr(args, "lockbox_size", 0.0))
    use_lockbox_protocol = dev_size > 0 or lockbox_size > 0
    heldout_size = dev_size if use_lockbox_protocol else test_size
    total_heldout = heldout_size + val_size + lockbox_size
    if (
        heldout_size <= 0
        or val_size < 0
        or lockbox_size < 0
        or total_heldout >= 1
    ):
        raise ValueError(
            "held-out sizes must be non-negative, the development/test size "
            "must be positive, and their sum must be less than 1"
        )

    groups = data_df[group_column].astype(str).to_numpy()
    all_indices = np.arange(len(data_df))
    split_file = getattr(args, "split_file", None)
    split_strategy = str(
        getattr(args, "split_strategy", "group")
    ).lower()

    if not _is_none_like(split_file) and Path(split_file).exists():
        with open(split_file, "r", encoding="utf-8") as handle:
            metadata = json.load(handle)
        expected = {
            "seed": seed,
            "group_column": group_column,
            "test_size": test_size,
            "val_size": val_size,
        }
        if use_lockbox_protocol:
            expected.update(
                {"dev_size": dev_size, "lockbox_size": lockbox_size}
            )
        for key, value in expected.items():
            if metadata.get(key) != value:
                raise ValueError(
                    f"split metadata mismatch for '{key}': "
                    f"file={metadata.get(key)!r}, config={value!r}"
                )
        if (
            split_strategy == "group_stratified"
            and metadata.get("protocol")
            != "train_val_test_group_stratified"
        ):
            raise ValueError(
                "group_stratified requires a manifest generated by "
                "scripts/make_splits.py"
            )
        assignments = metadata["assignments"]
        missing = sorted(set(groups) - set(assignments))
        if missing:
            raise ValueError(f"split file is missing {len(missing)} groups")
    else:
        if split_strategy == "group_stratified":
            raise FileNotFoundError(
                "group_stratified never creates a fallback random split; "
                f"generate the frozen manifest first: {split_file}"
            )
        outer = GroupShuffleSplit(
            n_splits=1, test_size=heldout_size, random_state=seed
        )
        remaining_pos, heldout_pos = next(
            outer.split(all_indices, groups=groups)
        )
        if val_size > 0:
            relative_val_size = val_size / (1.0 - heldout_size)
            inner = GroupShuffleSplit(
                n_splits=1, test_size=relative_val_size, random_state=seed + 1
            )
            train_lockbox_rel, val_rel = next(
                inner.split(remaining_pos, groups=groups[remaining_pos])
            )
            train_lockbox_pos = remaining_pos[train_lockbox_rel]
            val_pos = remaining_pos[val_rel]
        else:
            train_lockbox_pos = remaining_pos
            val_pos = np.array([], dtype=int)

        if lockbox_size > 0:
            relative_lockbox_size = lockbox_size / (
                1.0 - heldout_size - val_size
            )
            lockbox_splitter = GroupShuffleSplit(
                n_splits=1,
                test_size=relative_lockbox_size,
                random_state=seed + 2,
            )
            train_rel, lockbox_rel = next(
                lockbox_splitter.split(
                    train_lockbox_pos,
                    groups=groups[train_lockbox_pos],
                )
            )
            train_pos = train_lockbox_pos[train_rel]
            lockbox_pos = train_lockbox_pos[lockbox_rel]
        else:
            train_pos = train_lockbox_pos
            lockbox_pos = np.array([], dtype=int)

        heldout_name = "dev" if use_lockbox_protocol else "test"
        assignments = {}
        for split_name, positions in (
            ("train", train_pos),
            ("val", val_pos),
            (heldout_name, heldout_pos),
            ("lockbox", lockbox_pos),
        ):
            for group in np.unique(groups[positions]):
                assignments[str(group)] = split_name

        if not _is_none_like(split_file):
            split_path = Path(split_file)
            split_path.parent.mkdir(parents=True, exist_ok=True)
            metadata = {
                "seed": seed,
                "group_column": group_column,
                "test_size": test_size,
                "val_size": val_size,
                "dev_size": dev_size,
                "lockbox_size": lockbox_size,
                "protocol": (
                    "train_val_dev_lockbox"
                    if use_lockbox_protocol
                    else "train_val_test"
                ),
                "n_rows": int(len(data_df)),
                "n_groups": int(len(np.unique(groups))),
                "assignments": assignments,
            }
            tmp_path = split_path.with_suffix(split_path.suffix + ".tmp")
            with open(tmp_path, "w", encoding="utf-8") as handle:
                json.dump(metadata, handle, indent=2, sort_keys=True)
            tmp_path.replace(split_path)

    split_names = (
        ("train", "val", "dev", "lockbox")
        if use_lockbox_protocol
        else ("train", "val", "test")
    )
    return {
        split_name: all_indices[
            np.array([assignments[str(group)] == split_name for group in groups])
        ]
        for split_name in split_names
    }


def _random_split_indices(data_df, args, stratify_labels=None, eligible_indices=None):
    """Legacy site-level split with an optional validation partition."""
    indices = (
        np.arange(len(data_df))
        if eligible_indices is None
        else np.asarray(eligible_indices, dtype=int)
    )
    test_size = float(getattr(args, "test_size", 0.15))
    val_size = float(getattr(args, "val_size", 0.0))
    seed = int(getattr(args, "seed", 42))

    train_val, test = train_test_split(
        indices,
        test_size=test_size,
        stratify=(
            stratify_labels[indices] if stratify_labels is not None else None
        ),
        random_state=seed,
    )
    if val_size <= 0:
        return {"train": train_val, "val": np.array([], dtype=int), "test": test}

    relative_val_size = val_size / (1.0 - test_size)
    inner_stratify = (
        stratify_labels[train_val] if stratify_labels is not None else None
    )
    train, val = train_test_split(
        train_val,
        test_size=relative_val_size,
        stratify=inner_stratify,
        random_state=seed + 1,
    )
    return {"train": train, "val": val, "test": test}

# --- 2. 优化后的核心处理函数 (Numpy Vectorization) ---

def parse_column_to_numpy(series_col):
    """Parse finite 1-D vectors with the original float32 conversion.

    Accept whitespace-separated NumPy-style or comma-separated arrays without
    evaluating Python expressions or silently discarding invalid values.
    """
    res = []
    column_name = getattr(series_col, "name", "spectrum")
    row_ids = series_col.index if isinstance(series_col, pd.Series) else range(len(series_col))
    for row_id, value in zip(row_ids, series_col):
        try:
            if isinstance(value, str):
                text = value.strip().replace("\\n", " ")
                if text.startswith("[") and text.endswith("]"):
                    text = text[1:-1]
                if "[" in text or "]" in text:
                    raise ValueError("expected one flat vector with balanced brackets")
                if "," in text and any(not part.strip() for part in text.split(",")):
                    raise ValueError("missing value between commas")
                tokens = text.replace(",", " ").split()
                array = np.asarray([float(token) for token in tokens], dtype=np.float32)
            else:
                array = np.asarray(value, dtype=np.float32)
            if array.ndim != 1 or array.size == 0:
                raise ValueError("expected a nonempty one-dimensional vector")
            if not np.isfinite(array).all():
                raise ValueError("all vector values must be finite")
        except (TypeError, ValueError, OverflowError) as exc:
            raise ValueError(f"Invalid {column_name!r} at row {row_id!r}: {exc}") from exc
        res.append(array)
    return res

def X_log_normalize_optimized(data_list_of_arrays, min_log_data, max_log_data, log_base=np.e):
    """
    [加速] X轴归一化
    """
    # 1. 拼接所有数据以进行批量运算 (如果 min/max 不由外部指定，需在此计算，但 args 提供了)
    # 这里直接对每个 array 进行向量化操作
    normalized_list = []
    denom = max_log_data - min_log_data
    if denom == 0: denom = 1.0

    for arr in data_list_of_arrays:
        if not np.isfinite(arr).all() or np.any(arr <= 0):
            raise ValueError("Energy values must be finite and strictly positive before log scaling")
        # Log 变换
        if log_base == np.e:
            log_arr = np.log(arr)
        else:
            log_arr = np.log10(arr)
        
        # 归一化
        norm_arr = (log_arr - min_log_data) / denom
        normalized_list.append(norm_arr)
        
    return normalized_list

def Y_log_normalize_optimized(data_list_of_arrays):
    """
    [加速] Y轴归一化 (Min-Max per sample)
    """
    normalized_data = []
    epsilon = 1e-10
    
    for sub_arr in data_list_of_arrays:
        min_val = np.min(sub_arr)
        max_val = np.max(sub_arr)
        # 向量化计算
        tmp = (sub_arr - min_val) / (max_val - min_val + epsilon)
        normalized_data.append(tmp)
        
    return normalized_data

def add_noise_consistency_optimized(data_list_of_arrays, noise_level):
    """
    [加速且保真] 
    1. 使用 random.gauss 生成与原代码完全一致的噪声向量。
    2. 使用 Numpy 向量加法替代 zip 循环。
    """
    limit = float(noise_level)
    sigma = limit / 3.0
    
    # === 关键：保持随机数生成逻辑不变 ===
    # 原代码：[max(-limit, min(random.gauss(0, sigma), limit)) for _ in range(256)]
    noise_vector_list = [max(-limit, min(random.gauss(0, sigma), limit)) for _ in range(256)]
    noise_vector_np = np.array(noise_vector_list, dtype=np.float32)
    noise_len = len(noise_vector_np)
    
    noisy_data = []
    for arr in data_list_of_arrays:
        # === 关键：模拟 zip 的截断行为 ===
        # zip(arr, noise) 会以两者中最短的长度为准
        curr_len = len(arr)
        valid_len = min(curr_len, noise_len)
        
        # 向量加法 (只处理有效长度)
        # 如果 arr 比 256 长，原代码会截断后面的数据，这里保持一致
        # 如果 arr 比 256 短，原代码会截断噪声，这里保持一致
        new_arr = arr[:valid_len] + noise_vector_np[:valid_len]
        
        noisy_data.append(new_arr)
        
    return noisy_data

# --- 3. 优化后的 Dataset 类 ---

class MyDataset(data_utils.Dataset):
    @timer
    def __init__(self, dataset, args):
        self.data_list = []
        self.args = args
        self.metric_name = 'AUC'
        file = args.data_file 

        # 读取数据
        data_df = pd.read_csv(file, index_col=[0], comment='#')
        required_columns = {"XAS_Relative_energy", "XAS_Intensity", "center_atom_type"}
        missing_columns = sorted(required_columns - set(data_df.columns))
        if missing_columns:
            raise ValueError(f"Input CSV is missing required columns: {missing_columns}")
        if data_df.empty:
            raise ValueError("Input CSV contains no spectra")

        # 1. 快速解析数据 (得到 list of np.array)
        data_re = parse_column_to_numpy(data_df.loc[:, 'XAS_Relative_energy'])
        data_its = parse_column_to_numpy(data_df.loc[:, 'XAS_Intensity'])
        num_cont = int(args.num_cont)
        if num_cont <= 0 or num_cont % 2:
            raise ValueError("num_cont must be a positive even number of energy/intensity values")
        expected_points = num_cont // 2
        for row_id, energy, intensity in zip(data_df.index, data_re, data_its):
            if len(energy) != expected_points or len(intensity) != expected_points:
                raise ValueError(
                    f"Row {row_id!r} requires {expected_points} energy and intensity points; "
                    f"received {len(energy)} and {len(intensity)}. No truncation is performed."
                )
            if np.any(energy <= 0):
                raise ValueError(f"Row {row_id!r} has non-positive energy values; log scaling requires positive coordinates")

        # 2. X轴处理
        data_re = X_log_normalize_optimized(data_re, min_log_data=args.min_log_data, max_log_data=args.max_log_data, log_base=np.e)

        # 3. 添加噪声 (先加噪，后归一化 - 保持原逻辑)
        if not _is_none_like(getattr(args, "add_noise", None)):
            # 这里调用优化后的加噪函数，逻辑完全一致
            data_its = add_noise_consistency_optimized(data_its, args.add_noise)

        # 4. Y轴处理
        data_its = Y_log_normalize_optimized(data_its)

        try:
            tot_spec_in_list = []
            for r, i in zip(data_re, data_its):
                combined = np.empty(expected_points * 2, dtype=np.float32)
                combined[0::2] = r
                combined[1::2] = i
                tot_spec_in_list.append(combined)
            
            tot_spec_in = np.array(tot_spec_in_list)
            
        except Exception as e:
            print(f"Warning during vectorization: {e}. Falling back to slower loop.")
            tot_spec_in = np.array([np.ravel(np.column_stack((l1, l2))) for l1, l2 in zip(data_re, data_its)])

        ele_dict = args.ele_dict
        x_center_atom_type = np.array(data_df.loc[:, 'center_atom_type'])
        unknown_elements = sorted({str(v) for v in x_center_atom_type if v not in ele_dict})
        if unknown_elements:
            raise ValueError(f"Unknown absorber element(s): {unknown_elements}; supported: {sorted(ele_dict)}")
        x_center_atom_type = np.array([ele_dict[v] for v in x_center_atom_type])
            
        X_raw = np.concatenate((x_center_atom_type[:, np.newaxis], tot_spec_in), axis=1)


        n_aux = int(args.aux)
        if int(n_aux) <= 0 or int(n_aux) > len(data_df.columns) - 3:
            raise ValueError("aux must identify the trailing descriptor columns after the spectrum columns")
        tot_aux = np.array(data_df.iloc[:, (-n_aux):])
        
        self.is_multi_task = hasattr(args, 'multi_task') and isinstance(args.multi_task, list) and len(args.multi_task) > 0
        labels_dict = {}
        task_valid_masks = {}
        # Single-task datasets retain their historical task-specific filtering.
        # Joint datasets keep the union of rows with at least one valid target;
        # each head masks its own -1/NaN labels in loss and metrics. This gives
        # every descriptor exactly the same evaluation cohort as its Expert SPT
        # counterpart instead of silently shrinking all tasks to complete cases.
        valid_mask = np.zeros(len(data_df), dtype=bool) if self.is_multi_task else np.ones(len(data_df), dtype=bool)

        if self.is_multi_task:
            task_list = args.multi_task
        else:
            current_task_name = args.task if isinstance(args.task, str) else args.task['name']
            task_list = [current_task_name]

        print("task_list: ", task_list)
        for t_name in task_list:
            if not hasattr(args, t_name):
                if not self.is_multi_task and isinstance(args.task, dict):
                     t_conf = args.task
                else:
                    raise ValueError(f"Configuration for task '{t_name}' not found in args.")
            else:
                t_conf = getattr(args, t_name)

            raw_col = tot_aux[:, t_conf['idx']]

            if t_conf['mode'] == 'Cls':
                mp = dict(zip(t_conf['value'], t_conf['label']))
                processed_col = np.array([mp.get(v, -1) for v in raw_col])
                task_valid = processed_col >= 0
                min_samples = int(getattr(args, "min_class_samples", 3))
                min_groups = int(getattr(args, "min_class_groups", 1))
                valid_labels = pd.Series(processed_col[task_valid])
                sample_counts = valid_labels.value_counts()
                supported_classes = set(
                    sample_counts[sample_counts >= min_samples].index
                )
                group_column = getattr(args, "group_column", "material_id")
                if min_groups > 1 and group_column in data_df.columns:
                    valid_frame = pd.DataFrame(
                        {
                            "label": processed_col[task_valid],
                            "group": data_df.loc[task_valid, group_column]
                            .astype(str)
                            .to_numpy(),
                        }
                    )
                    group_counts = valid_frame.groupby("label")["group"].nunique()
                    supported_classes &= set(
                        group_counts[group_counts >= min_groups].index
                    )
                supported = task_valid & np.isin(
                    processed_col, list(supported_classes)
                )
                task_valid = supported
                # Rows from mapped but unsupported classes can remain in a
                # Joint dataset because another descriptor is valid there.
                # Replace their otherwise in-range class id with the same -1
                # sentinel used for unmapped labels so every downstream loss,
                # metric, and CSV export excludes them exactly as the
                # corresponding single-task dataset does.
                processed_col = processed_col.copy()
                processed_col[~task_valid] = -1
            else:
                processed_col = raw_col.astype(float)
                task_valid = np.isfinite(processed_col)

            if self.is_multi_task:
                valid_mask |= task_valid
            else:
                valid_mask &= task_valid
            
            labels_dict[t_name] = processed_col
            task_valid_masks[t_name] = task_valid
        
        stratify_labels = None
        
        if self.is_multi_task:
            strat_task_name = getattr(args, 'stratify_task', None)
            if strat_task_name and strat_task_name in labels_dict:
                t_conf = getattr(args, strat_task_name)
                if t_conf['mode'] == 'Cls':
                    stratify_labels = labels_dict[strat_task_name]
                else:
                    print(f"Warning: stratify_task '{strat_task_name}' is Regression. Falling back to random split.")
        else:
            t_name = task_list[0]
            if not self.is_multi_task and isinstance(args.task, dict):
                 t_conf = args.task
            else:
                 t_conf = getattr(args, t_name)

            if t_conf['mode'] == 'Cls':
                stratify_labels = labels_dict[t_name]
        
        if dataset == 'infer':
            final_indices = np.where(valid_mask)[0]
            
        elif dataset in ['train', 'val', 'test', 'dev', 'lockbox']:
            if dataset == "lockbox" and not bool(
                getattr(args, "allow_lockbox_access", False)
            ):
                raise PermissionError(
                    "Lockbox access is disabled. Use the explicit frozen-model "
                    "lockbox evaluation workflow."
                )
            split_strategy = str(
                getattr(args, "split_strategy", "random")
            ).lower()
            if split_strategy in {"group", "group_stratified"}:
                split_indices = _group_split_indices(data_df, args)
            elif split_strategy == "random":
                if dataset in {"dev", "lockbox"}:
                    raise ValueError(
                        "dev/lockbox protocol requires split_strategy='group'"
                    )
                split_indices = _random_split_indices(
                    data_df,
                    args,
                    stratify_labels=stratify_labels,
                    eligible_indices=np.where(valid_mask)[0],
                )
            else:
                raise ValueError(
                    f"unknown split_strategy '{split_strategy}'; use "
                    "'group_stratified', 'group', or 'random'"
                )

            requested_split = dataset
            if dataset == "test" and "test" not in split_indices:
                requested_split = "dev"
            final_indices = np.intersect1d(
                split_indices[requested_split],
                np.where(valid_mask)[0],
                assume_unique=False,
            )
        else:
            raise ValueError(
                "dataset must be one of: train, val, dev, test, lockbox, infer"
            )

        self.indices = final_indices
        self.split_name = dataset
        self.task_valid_masks = {
            task: mask[final_indices]
            for task, mask in task_valid_masks.items()
        }
        
        if len(final_indices) == 0:
            self.cate = np.array([])
            self.cont = np.array([])
            self.label = []
        else:
            text_col_num = 1
            self.cate = X_raw[final_indices, :text_col_num]
            self.cont = X_raw[final_indices, text_col_num:]
            
            if self.is_multi_task:
                self.label = {}
                for t_name, t_labels in labels_dict.items():
                    self.label[t_name] = t_labels[final_indices]
            else:
                t_name = task_list[0]
                self.label = labels_dict[t_name][final_indices]

    def __getitem__(self, idx):
        cont = self.cont[idx]
        cate = self.cate[idx]
        
        if self.is_multi_task:
            label_dict = {}
            for t_name, t_data in self.label.items():
                val = t_data[idx]
                if hasattr(self.args, t_name):
                    mode = getattr(self.args, t_name)['mode']
                else:
                    mode = 'Cls' if isinstance(val, (int, np.integer)) else 'Reg'
                
                if mode == 'Cls':
                      label_dict[t_name] = torch.tensor(val, dtype=torch.long)
                else:
                      label_dict[t_name] = torch.tensor(val, dtype=torch.float)
            
            return torch.LongTensor(cate), torch.FloatTensor(cont), label_dict
            
        else:
            label = self.label[idx] # scalar or array scalar
            
            if isinstance(self.args.task, dict):
                 mode = self.args.task['mode']
            else:
                 mode = getattr(self.args, self.args.task)['mode']

            # squeeze() 处理维度
            if mode == 'Cls':
                 return torch.LongTensor(cate), torch.FloatTensor(cont), torch.LongTensor([label]).squeeze()
            else:
                 return torch.LongTensor(cate), torch.FloatTensor(cont), torch.FloatTensor([label]).squeeze()
    
    def evaluate(self, label, pred):
        return roc_auc_score(label.item(), pred[:,1].item())

    def __len__(self):
        if self.is_multi_task:
            if not self.label: return 0
            # 字典判空和取第一个key
            first_key = next(iter(self.label))
            return len(self.label[first_key])
        return len(self.label)

